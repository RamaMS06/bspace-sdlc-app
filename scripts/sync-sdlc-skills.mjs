// Copies BUMA's bspace-sdlc-skills plugin into packages/skills/agent-plugin, the plugin the desktop app
// bundles and loads into every Claude session (src-tauri: plugin_dir). The plugin's own repo stays the
// source of truth; run this after it changes.
//
//   pnpm skills:sync
//
// BSPACE_SKILLS_DIR points at another copy of the plugin (default: the sibling checkout
// ../bspace-fe-skills/plugins/bspace-sdlc-skills).
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(process.env.BSPACE_SKILLS_DIR ?? join(root, '../bspace-fe-skills/plugins/bspace-sdlc-skills'));
const dest = join(root, 'packages/skills/agent-plugin');

if (!existsSync(join(src, '.claude-plugin/plugin.json'))) {
  console.error(`No bspace-sdlc-skills plugin at ${src}. Set BSPACE_SKILLS_DIR to the plugin folder.`);
  process.exit(1);
}

rmSync(dest, { recursive: true, force: true });
// Claude Code reads .claude-plugin, skills and hooks; docs hold pages the hooks open. Codex and Cursor
// manifests aren't needed inside the app.
for (const part of ['.claude-plugin', 'skills', 'hooks', 'docs']) {
  if (existsSync(join(src, part))) cpSync(join(src, part), join(dest, part), { recursive: true });
}

const manifest = JSON.parse(readFileSync(join(src, '.claude-plugin/plugin.json'), 'utf8'));
writeFileSync(
  join(dest, 'SOURCE.md'),
  `# Bundled plugin\n\nCopied from \`bspace-sdlc-skills\` ${manifest.version} by \`pnpm skills:sync\`. Edit the plugin in its own repo, then sync again.\n`,
);
// An explicit import per SKILL.md, so the Skills screen and the preamble see every bundled skill.
const skills = readdirSync(join(dest, 'skills'), { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(dest, 'skills', d.name, 'SKILL.md')))
  .map((d) => d.name)
  .sort();
const ident = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
writeFileSync(
  join(root, 'packages/skills/src/sdlcSkills.generated.ts'),
  [
    '// GENERATED by scripts/sync-sdlc-skills.mjs. Do not edit by hand.',
    ...skills.map((n) => `import ${ident(n)} from '../agent-plugin/skills/${n}/SKILL.md?raw';`),
    '',
    `export const PLUGIN_VERSION = ${JSON.stringify(manifest.version)};`,
    '',
    '/** Every SKILL.md of the bundled bspace-sdlc-skills plugin, by folder name. */',
    'export const PLUGIN_SKILLS: Record<string, string> = {',
    ...skills.map((n) => `  ${JSON.stringify(n)}: ${ident(n)},`),
    '};',
    '',
  ].join('\n'),
);
console.log(`Synced bspace-sdlc-skills ${manifest.version} (${skills.length} skills) into packages/skills/agent-plugin`);

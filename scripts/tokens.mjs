// Turns the BUMA Design System color variables exported from Figma (design-tokens/buma/*.tokens.json,
// W3C design-token format) into CSS custom properties: Light on :root, Dark on .dark.
//
//   node scripts/tokens.mjs          write apps/desktop/src/styles/buma-tokens.css
//   node scripts/tokens.mjs --check  exit 1 when the CSS is out of date with the JSON
//
// Names follow the Figma path: text/extended/success/500 -> --buma-text-success-500,
// background/lightDark -> --buma-background-light-dark, shadow/10% -> --buma-shadow-10.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'design-tokens/buma');
const OUT = join(root, 'apps/desktop/src/styles/buma-tokens.css');

function kebab(segment) {
  return segment
    .replace(/%$/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase();
}

function flatten(tree, path = [], out = []) {
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith('$') || typeof node !== 'object' || node === null) continue;
    if ('$value' in node) {
      if (node.$type !== 'color') continue;
      const segments = [...path, key].filter((s) => s !== 'extended').map(kebab);
      out.push({ name: `--buma-${segments.join('-')}`, value: cssColor(node.$value), alias: aliasOf(node) });
    } else {
      flatten(node, [...path, key], out);
    }
  }
  return out;
}

/** Spacing and padding (Spacing.tokens.json, numbers in px): none, 2xs 4, xs 8, sm 12, md 16, lg 24, xl 32 … */
function spacing(tree) {
  return Object.entries(tree)
    .filter(([key, node]) => !key.startsWith('$') && node?.$type === 'number')
    .map(([key, node]) => ({ name: `--buma-spacing-${kebab(key)}`, value: node.$value === 0 ? '0' : `${node.$value}px`, alias: '' }));
}

function cssColor(v) {
  const alpha = v.alpha ?? 1;
  if (alpha >= 1) return v.hex.toLowerCase();
  const [r, g, b] = v.components.map((c) => Math.round(c * 255));
  return `rgb(${r} ${g} ${b} / ${Number(alpha.toFixed(2))})`;
}

function aliasOf(node) {
  return node.$extensions?.['com.figma.aliasData']?.targetVariableName ?? '';
}

function block(selector, tokens) {
  const width = Math.max(...tokens.map((t) => t.name.length));
  const lines = tokens.map((t) => `  ${(t.name + ':').padEnd(width + 1)} ${t.value};${t.alias ? ` /* ${t.alias} */` : ''}`);
  return `${selector} {\n${lines.join('\n')}\n}`;
}

const light = flatten(JSON.parse(readFileSync(join(SRC, 'Light.tokens.json'), 'utf8')));
const dark = flatten(JSON.parse(readFileSync(join(SRC, 'Dark.tokens.json'), 'utf8')));
const space = spacing(JSON.parse(readFileSync(join(SRC, 'Spacing.tokens.json'), 'utf8')));
const missing = light.map((t) => t.name).filter((n) => !dark.some((d) => d.name === n));
if (missing.length) throw new Error(`Dark.tokens.json lacks: ${missing.join(', ')}`);

const css = `/* GENERATED by scripts/tokens.mjs from design-tokens/buma/*.tokens.json. Do not edit by hand. */
/* BUMA Design System spacing (--buma-spacing-*) and semantic colors. Components use the app layer in tokens.css, not these directly.
   .light forces the light theme on a subtree (the welcome screen) even when the app is dark. */

${block(':root', space)}

${block(':root,\n.light', light)}

${block('.dark', dark)}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {}
  if (current !== css) {
    console.error('buma-tokens.css is out of date. Run: node scripts/tokens.mjs');
    process.exit(1);
  }
  console.log(`buma-tokens.css up to date (${light.length} tokens)`);
} else {
  writeFileSync(OUT, css);
  console.log(`wrote ${OUT} (${light.length} tokens x 2 themes)`);
}
